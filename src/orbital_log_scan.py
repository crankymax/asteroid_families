import sys
from pathlib import Path

import h5py as h5
import numpy as np
import pandas as pd

import datetime as datetime

import matplotlib as mpl
import matplotlib.pyplot as plt
mpl.use('Agg')

# boundary values
# semi major axis a
a_min = 1.8
a_max = 3.95
# eccentricity e
e_min = 0.0
e_max = 0.34
# inclination i (radians)
i_min = 0.0
i_max = 0.55

# indices in the particles array
SMA = 6
ECC = 7
INC = 8

ind_limits = {SMA: (a_min, a_max), ECC: (e_min, e_max), INC: (i_min, i_max)}


def particle_track(particle_names, particle_values, name):
    """
    Follow a particle through a run log by name. Rows shift when a particle is removed, so the
    row can't be used. Steps the run hasn't reached yet (all names empty) are left out.
    :param particle_names: particle_names[time, row] from the log
    :param particle_values: particle_values[time, row, value] from the log
    :param name: REBOUND particle name
    :return: (logged step indices, values[step, value] with zeros once the particle is removed,
             True for the steps the particle is in the sim)
    """
    logged = np.flatnonzero((particle_names != b'').any(axis=1))
    match = particle_names[logged] == name.encode('utf-8')
    if not match.any():
        raise ValueError(f"Particle {name} isn't in the log, particles must be named to be found")
    present = match.any(axis=1)
    rows = match.argmax(axis=1)
    track = np.zeros((len(logged), particle_values.shape[2]))
    track[present] = particle_values[logged[present], rows[present]]
    return logged, track, present


def scan_logs(particle_assignments_file: Path, results_dir: Path, project_dir: Path) -> tuple:
    """
    Iterate through the log files generated by the simulation and check for any parameters that exceed
    given values. It associates the particle in the simulation to the family asteroid that it is a clone
    of. The particles that exceed the values are written to a Pandas dataset.
    :param particle_assignments_file: The Pandas dataset that associates particles to asteroid clones
    :param results_dir: The logfile directory
    :param project_dir: The destination for the escaped_asteroids dataset
    :return: Metadata tuple about the processing
    """
    integration_time = None
    time_taken = []
    escaped_asteroid_data = list()
    particles_simulated = 0

    inner_solar = 0
    outer_solar = 0
    escaped_asteroids = set()
    particles_assigned = pd.read_hdf(particle_assignments_file.resolve())

    # scan the results dir for the HDF logs
    for pv_file in results_dir.glob('*.h5'):
        with h5.File(pv_file, 'r') as simulation_log:
            # The actives simulation log has no particles so skip it.
            if simulation_log.attrs['simulation'] == 'actives':
                continue

            # Determine the particle's asteroid
            sim_particles = particles_assigned[particles_assigned['sim_no'] == int(simulation_log.attrs['simulation'])]
            # Check the integration has completed
            if integration_time and integration_time != simulation_log.attrs['int_length']:
                print(f"Overall integration_time:{integration_time}, "
                      f"this {pv_file}:{simulation_log.attrs['int_length']}")
            else:
                integration_time = simulation_log.attrs['int_length']

            time_taken.append(simulation_log.attrs['clock_time'])

            # Load the logging arrays
            int_values = simulation_log['integration_time_values'][()]
            part_values = simulation_log['particle_values'][()]
            if 'particle_names' not in simulation_log:
                raise ValueError(f"{pv_file} has no particle_names, rerun it with the current rebound_run_sim")
            part_names = simulation_log['particle_names'][()]
            particles_simulated += len(sim_particles)

            # Check each assigned particle for values that are under or over limits.
            # A removed particle reads as zeros, so it escapes on a < a_min
            for ast in sim_particles.itertuples():
                steps, track, present = particle_track(part_names, part_values, ast.ast_name)
                for param_index, limits in ind_limits.items():
                    param_values = track[:, param_index]
                    outside = np.flatnonzero((param_values < limits[0]) | (param_values > limits[1]))
                    if len(outside) == 0:
                        continue
                    escaped_asteroids.add(f"{ast.ast_name}{''.join(ast.particle_types)}")
                    # The extremes while the particle is in the sim, not the zeros after removal
                    min_val = param_values[present].min()
                    max_val = param_values[present].max()
                    if param_index == SMA and min_val < a_min:
                        inner_solar += 1
                    if param_index == SMA and max_val > a_max:
                        outer_solar += 1
                    escaped_asteroid_data.append([ast.ast_name, ''.join(ast.particle_types),
                                                  simulation_log.attrs['simulation'],
                                                  ast.particle_number, param_index,
                                                  param_values[outside[0]],
                                                  int_values[steps[outside[0]]],
                                                  min_val,
                                                  max_val])

    escaped_ast_cols = ['ast_name', 'vectors', 'sim_no', 'particle_number', 'parameter', 'parameter_value',
                        'integration_year', 'min_val', 'max_val']
    escaped_ast_df = pd.DataFrame(escaped_asteroid_data, columns=escaped_ast_cols)
    escapees_file = project_dir / "escaped_asteroids.h5"

    # Some metadata is needed, so the lower level pd.HDFStore is used.
    with pd.HDFStore(str(escapees_file.resolve())) as hdf_store:
        hdf_store.put('escaped_asteroids', escaped_ast_df)
        hdf_store.get_storer('escaped_asteroids').attrs.metadata = {'integration_time': integration_time,
                                                                    'simulated': particles_simulated,
                                                                    'escaped': len(escaped_asteroids),
                                                                    'outer_solar': outer_solar,
                                                                    'inner_solar': inner_solar,
                                                                    'avg_walltime': np.mean(time_taken),
                                                                    }

    return len(escaped_asteroids), particles_simulated, np.mean(time_taken)


def plot_orbital_escapes(results_dir: Path, project_dir: Path):
    """
    Plots of the log files are created for all asteroids that lose 75% or more
    test-particles.
    :param results_dir: Location of the log files
    :param project_dir: Project directory
    :return: None
    """
    escapees_file = project_dir / "escaped_asteroids.h5"
    xlabel_time = 'Years after start of simulation [$10^9 ~ yr$]'

    # Read the escaped asteroids file
    ea_mmc3 = None
    with pd.HDFStore(str(escapees_file.resolve())) as ea_file:
        ea_mmc3 = ea_file.get('escaped_asteroids')

    # Get a list of all asteroids that have >= 75% of clones go missing
    ea_grouped1 = ea_mmc3[ea_mmc3.parameter == 6][['ast_name', 'vectors']].groupby('ast_name').size()
    asteroid_track_names = ea_grouped1[ea_grouped1 > (65 * 0.75)].index

    escaped_ast_sim = ea_mmc3[ea_mmc3.ast_name.isin(asteroid_track_names)][['ast_name', 'sim_no', 'particle_number']]
    escaped_ast_sim = escaped_ast_sim.drop_duplicates()
    for ast_name in asteroid_track_names:
        ast_array = escaped_ast_sim.loc[escaped_ast_sim.ast_name == ast_name].values
        print(ast_name)
        xkcd_colors = list(mpl.colors.XKCD_COLORS.keys())

        fig = plt.figure(figsize=(8, 8))
        fig.suptitle(f'Orbital Evolution for clones of asteroid {ast_name} ')
        gs = fig.add_gridspec(3, hspace=0)
        (ax1, ax2, ax3) = gs.subplots(sharex=True)

        # Iterate through the escaped asteroids
        for p_no, (particle_name, sim_file, _) in enumerate(ast_array):
            # Access the orbital parameter logs
            with h5.File(results_dir / f"pvals_{sim_file:0>5}.h5", 'r') as sim_log:
                # Unpack the H5
                steps, track, _ = particle_track(sim_log['particle_names'][()], sim_log['particle_values'][()],
                                                 particle_name)
                int_values = sim_log['integration_time_values'][()][steps]/(2*np.pi)
                # Find if the SMA goes to 0
                sma_0 = np.where(track[:, SMA] == 0.0)[0]
                # Set the x value range appropriately
                if len(sma_0) > 0:
                    graph_end = sma_0[0] + 1
                else:
                    graph_end = len(track)
                # Select a unique color
                color = xkcd_colors[p_no * 13]
                ax1.scatter(int_values[:graph_end], track[:graph_end, SMA],
                            s=5, marker='o', c=color)
                ax2.scatter(int_values[:graph_end], track[:graph_end, ECC],
                            s=5, marker='o', c=color)
                ax3.scatter(int_values[:graph_end], track[:graph_end, INC],
                            s=5, marker='o', c=color)
        plt.xlabel(xlabel_time)
        ax1.set_ylabel("Semi-major axis $a$ [AU]")
        ax1.label_outer()
        ax2.set_ylabel("Eccentricity $e$ []")
        ax2.label_outer()
        ax3.set_ylabel("Inclination $i$ [radian]")
        plt.savefig(project_dir / f"plots/orb_evol_{ast_name.replace(' ', '_')}.png", dpi=300)
        plt.close()

    print('Completed')


if __name__ == '__main__':
    print(sys.argv)
    clone_assignments = Path(sys.argv[1])
    cl_results_dir = Path(sys.argv[2])
    cl_project_dir = Path(sys.argv[3])
    escaped_c, simulated_c, avg_runtime = scan_logs(clone_assignments, cl_results_dir, cl_project_dir)
    print(f"Escaped asteroids:{escaped_c} Total simulated {simulated_c} "
          f"\nFraction escaped:{escaped_c/simulated_c}")
    print(f'Average run time {datetime.timedelta(seconds=avg_runtime)}')
    plot_orbital_escapes(cl_results_dir, cl_project_dir)
